import { afterEach, expect, it } from 'vitest';
import { EventEmitter } from 'node:events';
import net from 'node:net';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createApp } from '../src/server/app.js';
import type { Snapshot } from '../src/shared/types.js';

const cleanup: (() => Promise<unknown>)[] = [];
afterEach(async () => { for (const close of cleanup.splice(0).reverse()) await close(); });
it('one SSE stream sends revisions and reconnects with a complete current snapshot', async () => {
  const reservation = net.createServer(); await new Promise<void>(resolve => reservation.listen(0, '127.0.0.1', resolve));
  const port = (reservation.address() as net.AddressInfo).port; await new Promise<void>(resolve => reservation.close(() => resolve()));
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'agent-monitor-sse-')); cleanup.push(() => fs.rm(dir, { recursive: true, force: true }));
  await fs.writeFile(path.join(dir, 'index.html'), '<title>Agent Monitor</title>');
  const source = new EventEmitter() as EventEmitter & { current: Snapshot };
  source.current = { revision: 1, observedAt: new Date().toISOString(), sessions: [], allowances: [], diagnostics: [], collecting: false };
  const app = await createApp({ collector: source, port, clientDir: dir, workspace: dir });
  await app.listen({ port, host: '127.0.0.1' });
  cleanup.push(async () => { app.server.closeAllConnections(); await app.close(); });
  const base = `http://127.0.0.1:${port}`;
  const page = await fetch(base); const cookie = page.headers.get('set-cookie')!.split(';')[0]; await page.text();
  const abort = new AbortController(); cleanup.push(async () => abort.abort());
  const stream = await fetch(`${base}/api/events`, { headers: { cookie }, signal: abort.signal });
  expect(stream.headers.get('content-type')).toBe('text/event-stream');
  const reader = stream.body!.getReader();
  const first = new TextDecoder().decode((await reader.read()).value); expect(first).toContain('id: 1\nevent: snapshot'); expect(first).toContain('"revision":1');
  expect(source.listenerCount('snapshot')).toBe(1);
  source.current = { ...source.current, revision: 2, diagnostics: [{ code: 'new-session', level: 'info', message: 'A new native conversation appeared', at: new Date().toISOString() }] };
  source.emit('snapshot', source.current);
  const update = new TextDecoder().decode((await reader.read()).value); expect(update).toContain('id: 2'); expect(update).toContain('new-session');
  abort.abort(); await reader.cancel().catch(() => undefined);
  await new Promise(resolve => setTimeout(resolve, 30)); expect(source.listenerCount('snapshot')).toBe(0);
  const reconnect = new AbortController(); cleanup.push(async () => reconnect.abort());
  const resumed = await fetch(`${base}/api/events`, { headers: { cookie, 'last-event-id': '1' }, signal: reconnect.signal });
  const resumedReader = resumed.body!.getReader();
  const restored = new TextDecoder().decode((await resumedReader.read()).value); expect(restored).toContain('id: 2'); expect(restored).toContain('new-session');
  expect(source.listenerCount('snapshot')).toBe(1);
  reconnect.abort(); await resumedReader.cancel().catch(() => undefined);
});
